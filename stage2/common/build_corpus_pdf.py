def build_styles() -> dict[str, ParagraphStyle]:
    """[核心] 注册嵌入字体，并定义标题与正文的段落样式。"""
    # 1. [核心] 把 TTF 字体注册进 reportlab。之后用 FONT_NAME 引用它，生成 PDF 时字形会被子集嵌入。
    pdfmetrics.registerFont(TTFont(FONT_NAME, FONT_FILE))

    # 2. [核心] wordWrap="CJK" 让段落允许在任意两个汉字之间断行。
    #    换成默认的 None 会怎样：reportlab 只在空格处断行，
    #    中文没有空格，一整段会被当成一个"超长单词"，冲出页面右边界。
    body = ParagraphStyle(
        "body",
        fontName=FONT_NAME,
        fontSize=10.5,
        leading=17,          # [了解] 行距（两行基线之间的距离），约为字号的 1.6 倍，读起来不挤。
        wordWrap="CJK",
        spaceAfter=6,        # [了解] 段后空白，单位是 pt（1/72 英寸）。
        firstLineIndent=21,  # [了解] 首行缩进两个字（10.5pt × 2）。
    )

    # 3. [脚手架] 小节标题、部分标题、封面标题，只是字号和间距不同。
    section = ParagraphStyle(
        "section", parent=body, fontSize=13, leading=20,
        firstLineIndent=0, spaceBefore=10, spaceAfter=6,
    )
    part = ParagraphStyle(
        "part", parent=body, fontSize=15, leading=24,
        firstLineIndent=0, spaceBefore=16, spaceAfter=10,
    )
    title = ParagraphStyle(
        "title", parent=body, fontSize=20, leading=30,
        firstLineIndent=0, alignment=1, spaceAfter=18,  # [了解] alignment=1 表示居中。
    )
    return {"body": body, "section": section, "part": part, "title": title}


def build_story(styles: dict[str, ParagraphStyle]) -> list:
    """[了解] 把 SECTIONS 转成 platypus 的元素列表（reportlab 管它叫 story）。"""
    # 1. [了解] story 是一个从上往下排的元素清单，排版引擎按顺序把它们放到页面上，放不下就自动换页。
    story: list = [Paragraph("RAG 系统技术手册与星垣科技制度汇编", styles["title"])]

    # 2. [了解] 两层循环：先放部分标题，再依次放每个小节的标题和段落。
    #    小节之间不强制分页，让小节自然跨页。真实 PDF 里一节内容跨两页很常见，
    #    后面切分时会遇到"同一节被页码切成两段"的情况，这也是要观察的现象之一。
    for part_title, sections in SECTIONS:
        story.append(Paragraph(part_title, styles["part"]))
        for section_title, paragraphs in sections:
            story.append(Paragraph(section_title, styles["section"]))
            for text in paragraphs:
                story.append(Paragraph(text, styles["body"]))
        # 3. [脚手架] 两个部分之间多留一点空白，纯视觉效果。
        story.append(Spacer(1, 8 * mm))
    return story


def main() -> None:
    """[脚手架] 生成 PDF 并打印统计信息。"""
    # 1. [脚手架] 确保输出目录存在。
    OUTPUT_PDF.parent.mkdir(parents=True, exist_ok=True)

    # 2. [了解] SimpleDocTemplate = 带页边距的单栏页面模板；build() 负责排版并写文件。
    doc = SimpleDocTemplate(
        str(OUTPUT_PDF),
        pagesize=A4,
        leftMargin=22 * mm, rightMargin=22 * mm,
        topMargin=20 * mm, bottomMargin=20 * mm,
        title="RAG 系统技术手册与星垣科技制度汇编",  # [了解] 写进 PDF 元数据，PyPDFLoader 读出来会带上。
    )
    doc.build(build_story(build_styles()))

    # 3. [脚手架] 统计：小节数、正文字数、页数（doc.page 是排版结束时的页码）。
    n_sections = sum(len(secs) for _, secs in SECTIONS)
    n_chars = sum(len(p) for _, secs in SECTIONS for _, paras in secs for p in paras)
    print(f"已生成：{OUTPUT_PDF}")
    print(f"小节数：{n_sections}　正文字数：{n_chars}　页数：{doc.page}")


if __name__ == "__main__":
    main()
