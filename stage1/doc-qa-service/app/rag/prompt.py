"""提示词层 —— 决定往模型里塞什么。

这是整个 RAG 里最容易被低估的一层。
模型本身是别人训练好的，检索出来的内容也定了，你唯一能调的就是这里。
答案会不会编造、会不会标出处、答不上来时会不会瞎猜，全由这一层决定。

**提示词（prompt）**：发给模型的那段文字。
它分两部分。
系统提示词（system prompt）写在最前面，用来设定模型的身份和必须遵守的规则。
用户消息（user message）是这一轮的具体输入，这里放检索到的资料和用户的问题。

函数速查表（吃什么 -> 吐什么 -> 谁会调它）
    SYSTEM_PROMPT
        一个字符串常量，就是那段规则。不是函数。
    USER_TEMPLATE
        一个字符串常量，里面有 {context} 和 {question} 两个待填的坑。
    format_context(docs)
        吃 list[Document] -> 吐一个字符串，形如
            [1] 来源：after-sales-policy.md · 售后服务政策 / 一、七天无理由退货
            自签收之日起 7 个自然日内……

            [2] 来源：...
        被 app/rag/pipeline.py 调用。
    build_prompt()
        吃：无参数 -> 吐一个 ChatPromptTemplate 对象。
        被 app/main.py 在启动时调一次。

阅读地图
    必读：SYSTEM_PROMPT 的五条规则、format_context 的编号规则
    扫读：build_prompt
"""

from langchain_core.documents import Document
from langchain_core.prompts import ChatPromptTemplate

# ===========================================================================
# 一、系统提示词
# ===========================================================================
# [核心] 这五条规则每一条都对应一个真实会出问题的地方，不是凑数的。
#
#   规则 1 管的是「编造」。
#       模型自己也知道一些电商常识，比如「七天无理由」。
#       但我们平台的政策可能和它知道的不一样。
#       不禁止它用自身知识，它就会把通用常识和我们的政策混着答。
#
#   规则 2 管的是「可核实」。
#       没有编号出处，用户和客服都没法验证这句话是不是真的。
#       出了纠纷时，能指着原文说「政策第几条写的」，和「AI 说的」是两回事。
#
#   规则 3 管的是「拒答」。
#       这是客服场景的生死线。
#       乱答一句退换货政策，平台是要赔钱的。
#       所以宁可说不知道，也不能猜。
#
#   规则 4 管的是「废话」。
#       模型很爱说「根据您提供的资料，我认为……」。
#       客服场景要的是一句话给到答案。
#
#   规则 5 管的是「数字」。
#       这是实测中最容易出错的地方。
#       资料写「7 个自然日」，模型可能答成「一周」。
#       写「首重 12 元、续重每公斤 6 元」，模型可能自作主张算出一个总价。
#       数字必须原样搬运。
#
# [了解] 提示词里不能出现单独的花括号 { }。
#        后面 ChatPromptTemplate 会把花括号当成待填的变量坑。
#        写了字面量的花括号，它会报「缺少变量」的错。
SYSTEM_PROMPT = """你是电商平台的客服知识库问答助手。

你必须遵守以下规则：

1. 只能依据【资料】部分的内容回答，不得使用你自己掌握的电商常识，不得推测。
2. 每一句结论后面标出依据的资料编号，格式为 [1]，引用多条时写成 [1][3]。
3. 如果【资料】里找不到答案，只回答这一句：根据现有资料无法回答。不要编造，不要给建议，不要说"你可以联系客服"。
4. 回答用中文，直接给结论，不要复述问题，不要说"根据资料"之类的开场白。
5. 涉及金额、天数、时效、比例等数字时，必须与资料原文完全一致，不得换算、不得改写、不得四舍五入。"""

# [核心] 用户消息的模板。
#        两个大括号里的名字是待填的坑，后面调用时按名字传值进去。
#        用【】把两部分框起来，是为了让模型清楚地分辨哪段是资料、哪段是问题。
#        直接把资料和问题拼在一起不做分隔，模型有时会把资料里的句子当成用户的提问。
USER_TEMPLATE = """【资料】
{context}

【问题】
{question}"""


# ===========================================================================
# 二、把检索结果拼成资料段
# ===========================================================================
def format_context(docs: list[Document]) -> str:
    """把检索到的块拼成一段带编号的文字。"""
    # [核心] 编号是整条链路的关键。
    #        这里给每一块标上 [1] [2] [3]，模型在答案里引用这些编号，
    #        后面 pipeline 再把编号映射回具体是哪一块。
    #        编号必须从 1 开始。对人来说第一条就是 1 号，模型也是这么理解的。
    #        用 0 开头的话，模型经常会自作主张改成从 1 开始，编号就对不上了。
    parts: list[str] = []

    # 步骤 1：从 1 开始编号，逐块处理。
    for no, doc in enumerate(docs, start=1):
        meta = doc.metadata

        # 步骤 2：把章节路径拼出来，跳过空的层级。
        #         有的块只有 h1 和 h2，没有三级标题，这时 meta.get("h3") 是 None。
        #         不过滤的话 join 会抛 TypeError，因为它不能把 None 和字符串连起来。
        section = " / ".join(
            x for x in (meta.get("h1"), meta.get("h2"), meta.get("h3")) if x
        )
        label = meta.get("source", "未知来源")
        if section:
            label = f"{label} · {section}"

        # 步骤 3：拼成「编号 + 来源」一行，正文接在下一行。
        parts.append(f"[{no}] 来源：{label}\n{doc.page_content.strip()}")

    # 用空行把各块隔开。只用一个换行的话，正文本身就带换行，
    # 块和块之间就分不出边界，模型可能把 [2] 的内容当成 [1] 的后半段。
    return "\n\n".join(parts)


# ===========================================================================
# 三、组装成 LangChain 的提示词模板
# ===========================================================================
def build_prompt() -> ChatPromptTemplate:
    """[了解] 把系统提示词和用户模板组装成一个可复用的模板对象。"""
    # 步骤 1：from_messages 接收一个列表，每一项是（角色, 内容）。
    #         "system" 是系统提示词，"human" 是用户说的话。
    #         还有一个角色叫 "ai"，表示模型之前说过的话，多轮对话才用得上。
    #         我们现在是单轮无状态，所以只有这两个。
    #
    # 步骤 2：返回的对象怎么用？调它的 invoke 方法，把坑填上：
    #             prompt.invoke({"context": "...", "question": "..."})
    #         得到的是一个消息列表，可以直接喂给模型。
    return ChatPromptTemplate.from_messages(
        [
            ("system", SYSTEM_PROMPT),
            ("human", USER_TEMPLATE),
        ]
    )
