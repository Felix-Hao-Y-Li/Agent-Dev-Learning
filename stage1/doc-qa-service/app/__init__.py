"""doc-qa-service —— 企业级文档问答服务。

分层：api（HTTP 层）/ schemas（对外契约）/ rag（业务层）/ core（工程地基）。

这个文件是**包的入口**。
Python 在导入 app 包里任何一个模块之前，都会先执行这个文件。
所以凡是「必须在其它库被导入之前完成」的设置，都放在这里。
"""

import os
from pathlib import Path

from dotenv import load_dotenv

_PROJECT_ROOT = Path(__file__).resolve().parents[1]

# ---------------------------------------------------------------------------
# 第一件事：把 .env 里的内容灌进真正的环境变量
# ---------------------------------------------------------------------------
# [核心] 这里容易产生一个疑问：app/core/config.py 里的 Settings 已经会读 .env 了，
#        为什么还要再来一次？
#
#        因为两者读进去的地方不同。
#        Settings 把 .env 读成**它自己的属性**，只有我们的代码能看到。
#        os.environ 是操作系统级的环境变量，**所有库都能看到**。
#
#        huggingface_hub、transformers 这些第三方库只认 os.environ。
#        它们不知道我们的 Settings 对象存在。
#        load_dotenv() 的作用就是把 .env 的内容放进 os.environ，让这些库也能读到。
#
# [了解] override 参数默认是 False。
#        意思是：如果某个变量在真实环境里已经有值了，就不用 .env 里的值覆盖它。
#        这个默认行为是对的。部署到线上时，环境变量由容器编排系统注入，
#        优先级应当高于代码仓库里的文件。
load_dotenv(_PROJECT_ROOT / ".env")

# ---------------------------------------------------------------------------
# 第二件事：把 HuggingFace 的两个开关拨到「适合服务进程」的位置
# ---------------------------------------------------------------------------
# [核心] HF_HUB_OFFLINE=1 的含义是：只用本地缓存里的模型，不要联网。
#
#        为什么服务要这样？
#        默认情况下，加载模型时它会联网去 HuggingFace 查一下有没有更新。
#        这带来三个问题。
#        第一，启动速度取决于国内到 HuggingFace 的网络状况，不可控。
#        第二，对方限流或宕机时，我们的服务启动会跟着变慢甚至失败。
#        第三，它会打印一条「unauthenticated requests」警告，污染日志。
#
#        **代价必须说清楚**：开了离线模式，如果本地缓存里没有这个模型，
#        它不会去下载，而是直接报错。
#        第一次下载模型时要临时把它设成 0。
#
# [核心] HF_HUB_DISABLE_PROGRESS_BARS=1 的含义是：不要打印进度条。
#
#        进度条是给人看的，写给终端时用 \r 回车符不断刷新同一行。
#        我们的服务约定 stdout 只输出一行一条的 JSON 日志。
#        混进来的进度条会让日志采集器解析失败。
#
# [了解] setdefault 的意思是「这个键没有值时才设」。
#        用它而不是直接赋值，是为了让部署环境能覆盖我们的默认值。
#        注意上面的 load_dotenv 已经先执行了，所以 .env 里写的值优先级更高。
os.environ.setdefault("HF_HUB_OFFLINE", "1")
os.environ.setdefault("HF_HUB_DISABLE_PROGRESS_BARS", "1")
